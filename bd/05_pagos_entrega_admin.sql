/*==============================================================*/
/* ATHLETIX - Mejoras pedidas por el docente                     */
/*  - PAGO: todo pago (tarjeta o transferencia) queda guardado   */
/*  - Entrega rápida: retiro en tienda o envío a domicilio       */
/*  - Orden de pedido con código de retiro y hora estimada       */
/*  - Se puede comprar todo el stock (sin tope de 10 unidades)   */
/*  - Datos completos del producto en la base para que el        */
/*    administrador los maneje                                   */
/* Ejecutar UNA vez después de 01 a 04. Todo o nada.             */
/*==============================================================*/
begin;

/*---------------- PRODUCTO: atributos que maneja el administrador ----------------*/
alter table producto add column if not exists prd_etiqueta varchar(20) null;
alter table producto add column if not exists prd_caracteristicas text null;   -- una por línea
alter table producto add column if not exists prd_ficha text null;             -- "Dato: valor" por línea

/*==============================================================*/
/* Table: PRODUCTO_IMAGEN  (fotos del producto, en orden)        */
/*==============================================================*/
create table if not exists producto_imagen (
   prd_codigo           varchar(10)    not null,
   pim_orden            int2           not null,
   pim_url              varchar(300)   not null,
   pim_descripcion      varchar(80)    not null,
   constraint pk_producto_imagen primary key (prd_codigo, pim_orden),
   constraint ckc_pim_orden check (pim_orden between 1 and 6),
   constraint fk_producto_productoimagen foreign key (prd_codigo) references producto (prd_codigo) on delete cascade
);

/*---------------- DETALLE_PEDIDO: se puede comprar todo el stock ----------------*/
alter table detalle_pedido drop constraint if exists ckc_dpe_cantidad;
alter table detalle_pedido add constraint ckc_dpe_cantidad check (dpe_cantidad >= 1);

/*---------------- PEDIDO: entrega, orden de pedido y tiempos ----------------*/
alter table pedido add column if not exists ped_entrega varchar(10) not null default 'Retiro';
alter table pedido add column if not exists ped_direccion varchar(150) null;
alter table pedido add column if not exists ped_ciudad varchar(40) null;
alter table pedido add column if not exists ped_referencia varchar(120) null;
alter table pedido add column if not exists ped_costo_envio numeric(10,2) not null default 0;
alter table pedido add column if not exists ped_codigo_retiro char(6) null;
alter table pedido add column if not exists ped_hora_estimada timestamptz null;
alter table pedido drop constraint if exists ckc_ped_entrega;
alter table pedido add constraint ckc_ped_entrega check (
  ped_entrega = 'Retiro' or (ped_entrega = 'Domicilio' and ped_direccion is not null and ped_ciudad is not null));
alter table pedido drop constraint if exists ckc_ped_valores;
alter table pedido add constraint ckc_ped_valores check (
  ped_subtotal >= 0 and ped_iva >= 0 and ped_costo_envio >= 0 and ped_total = ped_subtotal + ped_iva + ped_costo_envio);
update pedido set ped_codigo_retiro = upper(substr(md5(ped_numero::text || random()::text), 1, 6)) where ped_codigo_retiro is null;
update pedido set ped_hora_estimada = ped_fecha + interval '1 hour' where ped_hora_estimada is null;

/*==============================================================*/
/* Table: PAGO  (cada pago del pedido: tarjeta o transferencia)  */
/* Se guarda una copia de la marca y los últimos 4 dígitos para  */
/* que el registro no se pierda si el cliente borra su tarjeta.  */
/*==============================================================*/
create table if not exists pago (
   pag_codigo           int4           generated by default as identity,
   ped_numero           int4           not null,
   pag_metodo           varchar(13)    not null,
   mpa_codigo           int4           null,
   pag_marca            varchar(12)    null,
   pag_ultimos4         char(4)        null,
   pag_banco            varchar(40)    null,
   pag_referencia       varchar(20)    null,
   pag_monto            numeric(10,2)  not null,
   pag_fecha            timestamptz    not null default now(),
   pag_estado           varchar(10)    not null default 'Aprobado',
   constraint pk_pago primary key (pag_codigo),
   constraint ak_pago_pedido unique (ped_numero),
   constraint ckc_pag_metodo check (pag_metodo in ('Tarjeta', 'Transferencia')),
   constraint ckc_pag_datos check (
     (pag_metodo = 'Tarjeta' and pag_ultimos4 is not null) or
     (pag_metodo = 'Transferencia' and pag_banco is not null and pag_referencia is not null)),
   constraint ckc_pag_monto check (pag_monto > 0),
   constraint ckc_pag_estado check (pag_estado in ('Aprobado', 'Anulado')),
   constraint fk_pedido_pago foreign key (ped_numero) references pedido (ped_numero) on delete cascade,
   constraint fk_metodopago_pago foreign key (mpa_codigo) references metodo_pago (mpa_codigo) on delete set null
);

-- Los pagos de los pedidos que ya existían pasan a la tabla PAGO
insert into pago (ped_numero, pag_metodo, mpa_codigo, pag_marca, pag_ultimos4, pag_monto, pag_fecha, pag_estado)
select p.ped_numero, 'Tarjeta', p.mpa_codigo, coalesce(m.mpa_marca, 'Visa'), coalesce(m.mpa_ultimos4, '0000'), p.ped_total, p.ped_fecha,
       case when p.ped_estado = 'Cancelado' then 'Anulado' else 'Aprobado' end
  from pedido p left join metodo_pago m on m.mpa_codigo = p.mpa_codigo
 where not exists (select 1 from pago g where g.ped_numero = p.ped_numero);
alter table pedido drop column if exists mpa_codigo;

/*---------------- Seguridad por filas ----------------*/
alter table producto_imagen enable row level security;
alter table pago enable row level security;
drop policy if exists "catalogo visible" on producto_imagen;
create policy "catalogo visible" on producto_imagen for select using (true);
drop policy if exists "mis pagos" on pago;
create policy "mis pagos" on pago for select using (
  exists (select 1 from pedido p where p.ped_numero = pago.ped_numero and (p.cli_cedula = mi_cedula() or es_admin())));

-- El administrador maneja los productos como quiera (crear, editar, desactivar, borrar)
drop policy if exists "admin productos" on producto;
create policy "admin productos" on producto for all using (es_admin()) with check (es_admin());
drop policy if exists "admin tallas" on producto_talla;
create policy "admin tallas" on producto_talla for all using (es_admin()) with check (es_admin());
drop policy if exists "admin imagenes" on producto_imagen;
create policy "admin imagenes" on producto_imagen for all using (es_admin()) with check (es_admin());

grant select on producto_imagen to anon, authenticated;
grant insert, update, delete on producto, producto_talla, producto_imagen to authenticated;
grant select on pago to authenticated;
revoke all on pago from anon;

/*---------------- Crear pedido (una sola transacción) ----------------*/
drop function if exists crear_pedido(int2, int4, jsonb, uuid);
create or replace function crear_pedido(
  p_items jsonb, p_clave uuid, p_entrega text, p_tienda int2, p_ciudad text, p_direccion text, p_referencia text, p_pago jsonb)
returns table (ped_numero int4, ped_codigo text, ped_total numeric, ped_codigo_retiro char(6), ped_hora_estimada timestamptz)
language plpgsql security definer set search_path = public as $$
declare
  v_cedula   char(10) := mi_cedula();
  v_numero   int4;
  v_tienda   int2;
  v_subtotal numeric(12,2) := 0;
  v_iva      numeric(12,2);
  v_envio    numeric(10,2) := 0;
  v_total    numeric(12,2);
  v_hora     timestamptz;
  v_metodo   text := p_pago->>'metodo';
  v_tar_cod  int4;
  v_tar_marca varchar(12);
  v_tar_ult4 char(4);
  r          record;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión para comprar'; end if;
  if v_cedula is null then raise exception 'Completa tu perfil antes de comprar'; end if;

  -- Idempotencia: si el mismo intento de pago llega dos veces, se devuelve el pedido ya creado
  if p_clave is not null then
    return query select p.ped_numero, 'AX-' || to_char(p.ped_fecha, 'YYYY') || '-' || lpad(p.ped_numero::text, 5, '0'), p.ped_total, p.ped_codigo_retiro, p.ped_hora_estimada
      from pedido p where p.ped_clave = p_clave and p.cli_cedula = v_cedula;
    if found then return; end if;
  end if;

  -- Entrega: retiro en tienda (listo en 1 hora) o envío a domicilio express (2 a 3 horas)
  if p_entrega = 'Retiro' then
    select tie_codigo into v_tienda from tienda where tie_codigo = p_tienda;
    if v_tienda is null then raise exception 'La tienda de retiro no es válida'; end if;
    v_hora := now() + interval '1 hour';
  elsif p_entrega = 'Domicilio' then
    select tie_codigo into v_tienda from tienda where tie_ciudad = p_ciudad order by tie_codigo limit 1;
    if v_tienda is null then raise exception 'Por ahora solo enviamos a Quito y Guayaquil'; end if;
    if p_direccion is null or length(trim(p_direccion)) < 8 then raise exception 'Escribe la dirección completa de entrega'; end if;
    v_envio := 3.50;
    v_hora := now() + interval '3 hours';
  else
    raise exception 'Elige cómo recibir tu pedido';
  end if;

  -- Pago simulado: tarjeta guardada del cliente o transferencia con banco y número de comprobante
  if v_metodo = 'Tarjeta' then
    select mpa_codigo, mpa_marca, mpa_ultimos4 into v_tar_cod, v_tar_marca, v_tar_ult4 from metodo_pago
     where mpa_codigo = nullif(p_pago->>'tarjeta', '')::int4 and cli_cedula = v_cedula;
    if v_tar_cod is null then raise exception 'El método de pago no es válido'; end if;
  elsif v_metodo = 'Transferencia' then
    if coalesce(p_pago->>'banco', '') not in ('Banco Pichincha', 'Banco Guayaquil', 'Produbanco', 'Banco del Pacífico', 'Banco Internacional') then
      raise exception 'Elige el banco desde el que transferiste';
    end if;
    if coalesce(p_pago->>'referencia', '') !~ '^[0-9]{6,12}$' then
      raise exception 'El número de comprobante debe tener de 6 a 12 números';
    end if;
  else
    raise exception 'Elige cómo pagar';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'El carrito está vacío'; end if;
  if jsonb_array_length(p_items) > 60 then raise exception 'Demasiados productos en un solo pedido'; end if;
  if (select count(*) from pedido where cli_cedula = v_cedula and ped_fecha > now() - interval '1 minute') >= 5 then
    raise exception 'Hiciste demasiados pedidos seguidos. Espera un minuto.';
  end if;

  begin
    -- Bloqueo por fila en orden fijo: dos compras al mismo tiempo nunca venden más de lo que hay
    for r in
      select p.prd_codigo, p.prd_nombre, p.prd_precio, p.prd_usa_talla, p.prd_activo,
             coalesce(nullif(x->>'talla', ''), 'U') as talla,
             sum((x->>'cantidad')::int) as cantidad
        from jsonb_array_elements(p_items) x
        left join producto p on p.prd_codigo = x->>'producto'
       group by p.prd_codigo, p.prd_nombre, p.prd_precio, p.prd_usa_talla, p.prd_activo, coalesce(nullif(x->>'talla', ''), 'U')
       order by p.prd_codigo, 6
    loop
      if r.prd_codigo is null or not r.prd_activo then raise exception 'Un producto del carrito ya no está disponible'; end if;
      if r.cantidad is null or r.cantidad < 1 then raise exception 'La cantidad de "%" no es válida', r.prd_nombre; end if;
      if r.prd_usa_talla and r.talla = 'U' then raise exception 'Elige una talla para "%"', r.prd_nombre; end if;

      update producto_talla set pta_stock = pta_stock - r.cantidad
       where prd_codigo = r.prd_codigo and pta_talla = r.talla and pta_stock >= r.cantidad;
      if not found then
        raise exception 'No hay stock suficiente de "%"%', r.prd_nombre, case when r.talla = 'U' then '' else ' talla ' || r.talla end;
      end if;
      v_subtotal := v_subtotal + r.prd_precio * r.cantidad;
    end loop;

    v_iva := round(v_subtotal * 0.15, 2);
    v_total := v_subtotal + v_iva + v_envio;
    insert into pedido (cli_cedula, tie_codigo, ped_subtotal, ped_iva, ped_costo_envio, ped_total, ped_clave,
                        ped_entrega, ped_ciudad, ped_direccion, ped_referencia, ped_codigo_retiro, ped_hora_estimada)
    values (v_cedula, v_tienda, v_subtotal, v_iva, v_envio, v_total, p_clave,
            p_entrega, case when p_entrega = 'Domicilio' then p_ciudad end,
            case when p_entrega = 'Domicilio' then trim(p_direccion) end,
            case when p_entrega = 'Domicilio' then nullif(trim(coalesce(p_referencia, '')), '') end,
            upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6)), v_hora)
    returning pedido.ped_numero into v_numero;

    insert into detalle_pedido (ped_numero, prd_codigo, dpe_talla, dpe_cantidad, dpe_precio_unitario)
    select v_numero, p.prd_codigo, coalesce(nullif(x->>'talla', ''), 'U'), sum((x->>'cantidad')::int), p.prd_precio
      from jsonb_array_elements(p_items) x join producto p on p.prd_codigo = x->>'producto'
     group by p.prd_codigo, coalesce(nullif(x->>'talla', ''), 'U'), p.prd_precio;

    insert into pago (ped_numero, pag_metodo, mpa_codigo, pag_marca, pag_ultimos4, pag_banco, pag_referencia, pag_monto)
    values (v_numero, v_metodo,
            v_tar_cod, v_tar_marca, v_tar_ult4,
            case when v_metodo = 'Transferencia' then p_pago->>'banco' end,
            case when v_metodo = 'Transferencia' then p_pago->>'referencia' end,
            v_total);
  exception when unique_violation then
    if p_clave is not null then
      return query select p.ped_numero, 'AX-' || to_char(p.ped_fecha, 'YYYY') || '-' || lpad(p.ped_numero::text, 5, '0'), p.ped_total, p.ped_codigo_retiro, p.ped_hora_estimada
        from pedido p where p.ped_clave = p_clave and p.cli_cedula = v_cedula;
      if found then return; end if;
    end if;
    raise;
  end;

  return query select p.ped_numero, 'AX-' || to_char(p.ped_fecha, 'YYYY') || '-' || lpad(p.ped_numero::text, 5, '0'), p.ped_total, p.ped_codigo_retiro, p.ped_hora_estimada
    from pedido p where p.ped_numero = v_numero;
end $$;

/*---------------- Cambiar estado: al cancelar se devuelve el stock y se anula el pago ----------------*/
create or replace function cambiar_estado_pedido(p_numero int4, p_estado varchar)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_actual varchar;
  permitidos text[];
begin
  if not es_admin() then raise exception 'Solo un administrador puede cambiar el estado'; end if;
  select ped_estado into v_actual from pedido where ped_numero = p_numero for update;
  if not found then raise exception 'El pedido no existe'; end if;
  permitidos := case v_actual
    when 'Recibido'   then array['Preparando', 'Listo', 'Cancelado']
    when 'Preparando' then array['Listo', 'Cancelado']
    when 'Listo'      then array['Retirado', 'Cancelado']
    else array[]::text[] end;
  if not (p_estado = any (permitidos)) then raise exception 'No se puede pasar un pedido de "%" a "%"', v_actual, p_estado; end if;
  if p_estado = 'Cancelado' then
    update producto_talla t set pta_stock = t.pta_stock + d.dpe_cantidad
      from detalle_pedido d
     where d.ped_numero = p_numero and t.prd_codigo = d.prd_codigo and t.pta_talla = d.dpe_talla;
    update pago set pag_estado = 'Anulado' where ped_numero = p_numero;
  end if;
  update pedido set ped_estado = p_estado where ped_numero = p_numero;
end $$;

/*---------------- Panel del administrador ----------------*/
drop function if exists pedidos_admin();
create or replace function pedidos_admin()
returns table (ped_numero int4, ped_codigo text, ped_estado varchar, ped_total numeric, ped_fecha timestamptz,
               cliente text, cli_correo varchar, cli_telefono char(10), cli_cedula char(10),
               tie_nombre varchar, tie_horario varchar, productos text,
               ped_entrega varchar, ped_ciudad varchar, ped_direccion varchar, ped_referencia varchar,
               ped_codigo_retiro char(6), ped_hora_estimada timestamptz, pago text)
language plpgsql stable security definer set search_path = public as $$
begin
  if not es_admin() then raise exception 'Solo un administrador puede ver todos los pedidos'; end if;
  return query
  select p.ped_numero, 'AX-' || to_char(p.ped_fecha, 'YYYY') || '-' || lpad(p.ped_numero::text, 5, '0'),
         p.ped_estado, p.ped_total, p.ped_fecha,
         c.cli_nombres || ' ' || c.cli_apellidos, c.cli_correo, c.cli_telefono, c.cli_cedula,
         t.tie_nombre, t.tie_horario,
         (select string_agg(d.dpe_cantidad || ' × ' || pr.prd_nombre || case when d.dpe_talla = 'U' then '' else ' (talla ' || d.dpe_talla || ')' end, ', ')
            from detalle_pedido d join producto pr on pr.prd_codigo = d.prd_codigo where d.ped_numero = p.ped_numero),
         p.ped_entrega, p.ped_ciudad, p.ped_direccion, p.ped_referencia, p.ped_codigo_retiro, p.ped_hora_estimada,
         (select case when g.pag_metodo = 'Tarjeta' then g.pag_marca || ' •••• ' || g.pag_ultimos4
                      else 'Transferencia ' || g.pag_banco || ' · comprobante ' || g.pag_referencia end
                 || case when g.pag_estado = 'Anulado' then ' (anulado)' else '' end
            from pago g where g.ped_numero = p.ped_numero)
    from pedido p join cliente c on c.cli_cedula = p.cli_cedula join tienda t on t.tie_codigo = p.tie_codigo
   order by p.ped_fecha desc;
end $$;

revoke execute on function crear_pedido(jsonb, uuid, text, int2, text, text, text, jsonb) from public, anon;
grant  execute on function crear_pedido(jsonb, uuid, text, int2, text, text, text, jsonb) to authenticated;
revoke execute on function pedidos_admin() from public, anon;
grant  execute on function pedidos_admin() to authenticated;

commit;
