/* ATHLETIX - Migración: del modelo copiado de la clase          */
/* (PEDIDOCLIENTE, PAGOS, PRODUCTO_PEDCLI, TARJETA) a mis tablas */
/* con la forma de modelar de la clase.                          */
/* Conserva clientes, administradores, tarjetas, pedidos,        */
/* detalle, reseñas y stock. Todo o nada (una transacción).      */
