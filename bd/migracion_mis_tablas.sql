begin;

/* 1. Quitar políticas, vistas, triggers y funciones que se recrean */
do $$ declare r record; begin
  for r in select policyname, tablename from pg_policies where schemaname = 'public' loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;
drop view if exists vista_calificaciones;
drop view if exists vista_resenas;
drop trigger if exists tib_cliente on cliente;
drop trigger if exists tib_resena on resena;
drop function if exists crear_pedido(int2, int4, jsonb, uuid);
drop function if exists cambiar_estado_pedido(numeric, varchar);
drop function if exists pedidos_nuevos();
drop function if exists pedidos_admin();
drop function if exists tib_resena();
drop function if exists tib_cliente();

/* 2. Quitar atributos que la tienda no usa */
alter table categoria drop column if exists cat_slug;
alter table producto drop column if exists prd_imagen, drop column if exists prd_fecha_creacion;
alter table producto_talla rename column pta_existencia to pta_stock;
alter table producto_talla rename constraint ckc_pta_existencia to ckc_pta_stock;

/* 3. Reseña: una por cliente y producto (clave compuesta) */
alter table resena drop constraint pk_resena;
alter table resena drop constraint ak_resena_cliente_producto;
alter table resena drop column res_codigo, drop column res_autor;
alter table resena add constraint pk_resena primary key (cli_cedula, prd_codigo);

/* 4. Tablas nuevas */
create table metodo_pago (
   mpa_codigo           int4           generated by default as identity,
   cli_cedula           char(10)       not null,
   mpa_marca            varchar(12)    not null,
   mpa_ultimos4         char(4)        not null,
   mpa_titular          varchar(60)    not null,
   mpa_mes_vence        int2           not null,
   mpa_anio_vence       int2           not null,
   constraint pk_metodo_pago primary key (mpa_codigo),
   constraint ak_metodo_pago_cliente unique (cli_cedula, mpa_marca, mpa_ultimos4, mpa_mes_vence, mpa_anio_vence),
   constraint ckc_mpa_marca check (mpa_marca in ('Visa', 'Mastercard')),
   constraint ckc_mpa_ultimos4 check (mpa_ultimos4 ~ '^[0-9]{4}$'),
   constraint ckc_mpa_mes check (mpa_mes_vence between 1 and 12),
   constraint ckc_mpa_anio check (mpa_anio_vence >= 2026)
);

create table pedido (
   ped_numero           int4           not null default nextval('seq_ped_numero'),
   cli_cedula           char(10)       not null,
   tie_codigo           int2           not null,
   mpa_codigo           int4           null,
   ped_fecha            timestamptz    not null default now(),
   ped_estado           varchar(12)    not null default 'Recibido',
   ped_subtotal         numeric(10,2)  not null,
   ped_iva              numeric(10,2)  not null,
   ped_total            numeric(10,2)  not null,
   ped_clave            uuid           null,
   constraint pk_pedido primary key (ped_numero),
   constraint ak_pedido_clave unique (ped_clave),
   constraint ckc_ped_estado check (ped_estado in ('Recibido', 'Preparando', 'Listo', 'Retirado', 'Cancelado')),
   constraint ckc_ped_valores check (ped_subtotal >= 0 and ped_iva >= 0 and ped_total = ped_subtotal + ped_iva)
);

create table detalle_pedido (
   ped_numero           int4           not null,
   prd_codigo           varchar(10)    not null,
   dpe_talla            varchar(5)     not null default 'U',
   dpe_cantidad         int2           not null,
   dpe_precio_unitario  numeric(10,2)  not null,
   constraint pk_detalle_pedido primary key (ped_numero, prd_codigo, dpe_talla),
   constraint ckc_dpe_cantidad check (dpe_cantidad between 1 and 10),
   constraint ckc_dpe_precio check (dpe_precio_unitario > 0)
);

/* 5. Copiar los datos */
insert into metodo_pago (mpa_codigo, cli_cedula, mpa_marca, mpa_ultimos4, mpa_titular, mpa_mes_vence, mpa_anio_vence)
select tar_codigo, cli_cedula, tar_marca, tar_ultimos4, tar_titular, tar_mes_vence, tar_anio_vence from tarjeta;
select setval(pg_get_serial_sequence('metodo_pago', 'mpa_codigo'), coalesce((select max(mpa_codigo) from metodo_pago), 0) + 1, false);

insert into pedido (ped_numero, cli_cedula, tie_codigo, mpa_codigo, ped_fecha, ped_estado, ped_subtotal, ped_iva, ped_total, ped_clave)
select p.ped_numero::int4, p.cli_cedula, p.tie_codigo,
       (select g.tar_codigo from pagos g where g.ped_numero = p.ped_numero limit 1),
       p.ped_fecha, p.ped_estado, p.ped_subtotal, p.ped_iva, p.ped_total, p.ped_clave
  from pedidocliente p;

insert into detalle_pedido (ped_numero, prd_codigo, dpe_talla, dpe_cantidad, dpe_precio_unitario)
select ped_numero::int4, prd_codigo, ppc_talla, ppc_cantidad, ppc_precio from producto_pedcli;

/* 6. Borrar las tablas copiadas del modelo de la clase */
drop table producto_pedcli;
drop table pagos;
drop table pedidocliente;
drop table tarjeta;

